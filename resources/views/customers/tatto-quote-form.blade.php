    function saveTattoQuote() {
      var size = $("input[name='size']:checked").val();
      var color = $("input[name='color']:checked").val();
      var photoname = $("#photoname").val();
      var availability = $("#availability").val();
      var budget = $("input[name='budget']:checked").val();
      var when = $("input[name='when']:checked").val();
      var description = $("#description").val();
      var tattooZones = $("#tattooZones").val();
      var artistID = $("#artist_id").val();
      //alert(size);
      if (size == '' || color == '' || budget == '' || when == '' || availability == '') {
        //alert('select size');
        $("#sizeError").text('Size field is required.');
        $('#colorError').text('Color field is required.');
        $("#budgetError").text('Budget field is required.');
        $('#whenError').text('When get tatooted field is required.');
        $("#dateError").text('Date availability field is required.');

        $("#allError").text('Please fill the required fields');

      } else {
        var filename = "{{ route('tatto-quotes.store') }}";
        var request = $.ajax({
          url: filename,
          type: "POST",
          data: {
            size: size,
            color: color,
            budget: budget,
            when_get_tattooed: when,
            availability: availability,
            artist_id: artistID,
            description: description,
            reference_image: photoname,
            front_back_view: tattooZones
          },
          dataType: "json"
        });

        request.done(function(result) {
          // alert(result.message1);
          // alert(result.message2);
          if (result.flag == 1) {
            $("#success-msg").show();
            $("#success-msg").text(result.msg);
            //alert(msg);
            $("#sizeError").text('');
            $('#colorError').text('');
            $("#budgetError").text('');
            $('#whenError').text('');
            $("#dateError").text('');

            $("#allError").text('');

            setTimeout(function() {
              location.reload(true);
            }, 3000);

          }


        });
        request.fail(function(jqXHR, textStatus) {
          //alert(jqXHR.status);
          if (jqXHR.status === 422) {
            const errors = jqXHR.responseJSON.errors;
            $('#sizeError').text(errors.size ? errors.size[0] : '');
            $('#colorError').text(errors.color ? errors.color[0] : '');
          }
        });

      }
    }

