    function addPoint(dataKey, element) {
      // Get the bounding box of the clicked path
      const bbox = element.getBBox();
      const cx = bbox.x + bbox.width / 2;
      const cy = bbox.y + bbox.height / 2;

      // Check if point already exists (shouldn't happen, but just in case)
      const existingPoints = document.querySelectorAll(`.selected-point[data-key="${dataKey}"]`);
      if (existingPoints.length > 0) return;

      // Create a circle element
      const circle = document.createElementNS('http://www.w3.org/2000/svg', 'circle');
      circle.setAttribute('cx', cx);
      circle.setAttribute('cy', cy);
      circle.setAttribute('r', '6');
      circle.setAttribute('fill', 'var(--selection-color)');
      circle.setAttribute('data-key', dataKey);
      circle.classList.add('selected-point');

      // Add the circle to the SVG
      element.parentNode.appendChild(circle);
    }

    function removePoint(dataKey) {
